/**
 * 发现类工具（`sys_glob` / `sys_grep`）默认排除的目录模式。
 *
 * 依赖树与版本库目录是最大的噪音源：在真实仓库里 `**\/*` 会把输出上限全部吃光，使工具失去作用。
 * 这是有意的默认值而非隐藏策略，已写入两个工具的描述，调用方可以据此调整模式。
 *
 * 放在共享文件里而不是各自定义，是为了让「默认排除了什么」只有一处事实来源——两个工具的排除范围
 * 一旦不一致，调用方就无法推断为什么同样的模式在两边结果不同。
 */
export const DEFAULT_DISCOVERY_EXCLUDES: readonly string[] = Object.freeze([
  "node_modules/**",
  "**/node_modules/**",
  ".git/**",
  "**/.git/**",
]);
